/**
 * @internal
 */
export function generateViteConfig(): string {
    const config = [
        `import { defineConfig } from "@forsakringskassan/vite-lib-config/vite";`,
        `import { defineTestConfig } from "@forsakringskassan/vitest-config-jsdom";`,
        ``,
        `export default defineConfig({`,
        `    test: defineTestConfig(),`,
        `});`,
    ]
        .map((it) => `${it}\n`)
        .join("");
    return [boilerplate, config].join("\n\n");
}

/* eslint-disable-next-line @typescript-eslint/no-unnecessary-type-parameters -- used to lie about the return value */
async function readJsonFile<T = unknown>(
    cwd: string,
    filename: string,
): Promise<{ data: T; indent: string; trailer: string }> {
    const filePath = path.join(cwd, filename);
    const content = await fs.readFile(filePath, "utf8");
    const data = JSON.parse(content) as T;
    const { indent } = detectIndent(content);
    const trailer = content.endsWith("\n") ? "\n" : "";
    return { data, indent, trailer };
}

async function writeJsonFile(
    cwd: string,
    filename: string,
    content: string,
): Promise<void> {
    const filePath = path.join(cwd, filename);
    await fs.writeFile(filePath, content, "utf8");
    console.log(filename, "written");
}

/**
 * @internal
 */
export function updateBuildScripts(
    pkg: PackageJson,
    options: Pick<
        Options,
        "enableApiExtractor" | "enableSelectors" | "enablePageobjects"
    >,
): PackageJson {
    const result = { ...pkg, scripts: { ...pkg.scripts } };
    const haveBuildMock = Boolean(result.scripts["build:mock"]);
    const buildSelectors = options.enableSelectors || options.enablePageobjects;
    result.scripts.build = [
        "run-s",
        "build:lib",
        haveBuildMock ? "build:mock" : null,
        buildSelectors ? "build:selectors" : null,
        "build:dts",
        options.enableApiExtractor ? "build:api" : null,
    ]
        .filter(Boolean)
        .join(" ");
    result.scripts["build:api"] = options.enableApiExtractor
        ? "fk-api-extractor api-extractor.*.json"
        : undefined;
    result.scripts["build:dts"] = "vue-tsc -b";
    result.scripts["build:lib"] = "fk-build-vue-lib --clean";
    result.scripts["build:selectors"] = buildSelectors
        ? "fk-build-selectors"
        : undefined;
    delete result.scripts["build:pageobject"];
    result.scripts.prebuild = undefined;
    return result;
}

async function writeBuildScripts(cwd: string, options: Options): Promise<void> {
    const result = await readJsonFile<PackageJson>(cwd, "package.json");
    const { data: pkg, indent, trailer } = result;
    const updated = JSON.stringify(
        updateBuildScripts(pkg, options),
        undefined,
        indent,
    );
    await writeJsonFile(cwd, "package.json", `${updated}${trailer}`);
}

async function findApiExtractorReportFolder(
    cwd: string,
): Promise<string | null> {
    const { findUp } = await import("find-up");
    const absolutePath = await findUp("package-lock.json", { cwd });

    /* use default path if not found */
    if (!absolutePath) {
        return null;
    }

    /* use default path if found in the current directory */
    const rootDir = path.dirname(absolutePath);
    if (path.resolve(cwd) === rootDir) {
        return null;
    }

    return path.relative(cwd, path.join(rootDir, "etc")).replaceAll("\\", "/");
}

async function findCypressConfigPath(cwd: string): Promise<string> {
    const { findUp } = await import("find-up");
    const absolutePath = await findUp("cypress/tsconfig.json", { cwd });
    if (absolutePath) {
        return path.relative(cwd, absolutePath).replaceAll("\\", "/");
    }
    return "./cypress/tsconfig.json";
}

function shouldPrune(filename: string): boolean {
    if (filename.startsWith("tsconfig.") && filename.endsWith(".json")) {
        return true;
    }
    if (filename.startsWith("api-extractor.") && filename.endsWith(".json")) {
        return true;
    }
    return false;
}

function flagEnabled(value: boolean): string {
    return value ? styleText("green", "enabled") : styleText("red", "disabled");
}

/**
 * @public
 */
export async function run(cwd: string, argv: string[]): Promise<void> {
    const flags = new Set(argv.filter((it) => it.startsWith("--")));

    if (flags.has("--help")) {
        console.log("usage: fk-write-config [OPTIONS..]");
        console.log(`
  --help                     Show this help.
  --with-api-extractor       Use @microsoft/api-extractor.
  --with-jest                Use Jest as test runner.
  --with-vitest              Use Vitest as test runner.
`);
        return;
    }

    const { data: pkg } = await readJsonFile<PackageJson>(cwd, "package.json");

    /* sanity check: if the package does not use
     * `@forsakringskassan/vite-lib-config` the configuration should not be
     * written either */
    if (!pkg.devDependencies?.["@forsakringskassan/vite-lib-config"]) {
        console.error(
            `The "${pkg.name}" does not use "@forsakringskassan/vite-lib-config".`,
        );
        console.error(`Skipping writing configuration.`);
        return;
    }

    const apiExtractorReportFolder = await findApiExtractorReportFolder(cwd);
    const cypressConfigPath = await findCypressConfigPath(cwd);
    const testRunner = detectTestRunner(flags);
    const options: Options = {
        name: pkg.name,
        apiExtractorReportFolder,
        cypressConfigPath,
        testRunner,
        enableApiExtractor: flags.has("--with-api-extractor"),
        enablePageobjects: Boolean(pkg.exports?.["./cypress"]),
        enableSelectors: Boolean(pkg.exports?.["./selectors"]),
    };
    const generated = new Map<string, string | null | Promise<string | null>>([
        ["api-extractor.json", null],
        ["api-extractor.lib.json", generateApiExtractorLib(options)],
        ["api-extractor.cypress.json", generateApiExtractorCypress(options)],
        [
            "api-extractor.selectors.json",
            generateApiExtractorSelectors(options),
        ],
        ["tsconfig.json", generateTsconfig(options)],
        ["tsconfig.lib.json", generateTsconfigLib(options)],
        ["tsconfig.cypress.json", generateTsconfigCypress(options)],
        ["tsconfig.selectors.json", generateTsconfigSelectors(options)],
        ["tsconfig.pageobjects.json", generateTsconfigPageobjects(options)],
        ["vite.config.ts", null],
        ["vite.config.mts", generateViteConfig()],
        ["vitest.setup.ts", null],
    ]);

    console.group("Writing configuration files");
    console.log("API Extractor:", flagEnabled(options.enableApiExtractor));
    console.log("Cypress pageobjects:", flagEnabled(options.enablePageobjects));
    console.log("Selector objects:", flagEnabled(options.enableSelectors));
    console.log("Test runner:", styleText("cyan", testRunner));
    console.log();

    /* write new files */
    const written = new Set<string>();
    const omitted = new Set<string>();
    for (const [filename, promise] of generated) {
        const content = await promise;
        if (content) {
            await writeJsonFile(cwd, filename, content);
            written.add(filename);
        } else {
            omitted.add(filename);
        }
    }

    /* remove any other tsconfig files */
    const entries = await fs.readdir(cwd);
    for (const entry of entries) {
        if (written.has(entry)) {
            continue;
        }

        if (omitted.has(entry) || shouldPrune(entry)) {
            await fs.unlink(path.join(cwd, entry));
            console.log(entry, "removed");
        }
    }

    await writeBuildScripts(cwd, options);

    console.groupEnd();
    console.log();
}
