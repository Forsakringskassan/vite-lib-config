import fs from "node:fs/promises";
import path from "node:path";
import { styleText } from "node:util";
import detectIndent from "detect-indent";

const boilerplate = `/* This file was generated by @forsakringskassan/vite-lib-config. Changes may be overwritten! */`;

/**
 * @internal
 */
export interface PackageJson {
    name: string;
    scripts?: Partial<Record<string, string>>;
    exports?: Record<string, unknown>;
    devDependencies?: Record<string, string>;
}

interface TSConfig {
    extends?: string | string[];
    references?: Array<{ path: string }>;
    compilerOptions?: {
        declarationDir?: string;
        types?: string[];
        paths?: Record<string, string[] | undefined>;
    };
    include?: string[];
    exclude?: string[];
}

/**
 * @internal
 */
export interface Options {
    /** name from package.json */
    name: string;

    /** path to "etc" folder or null to use default */
    apiExtractorReportFolder: string | null;

    /** path to cypress tsconfig */
    cypressConfigPath: string;

    /** test runner used in this repository */
    testRunner: "jest" | "vitest";

    /* true if api-extractor is detected */
    enableApiExtractor: boolean;

    /* true if selector objects are present */
    enableSelectors: boolean;

    /* true if cypress pageobjects are present */
    enablePageobjects: boolean;
}

function detectTestRunner(flags: Set<string>): "jest" | "vitest" {
    if (flags.has("--with-jest")) {
        return "jest";
    }
    if (flags.has("--with-vitest")) {
        return "vitest";
    }
    return "vitest";
}

async function serializeJson(data: unknown): Promise<string> {
    const { format, resolveConfig } = await import("prettier");
    const content = JSON.stringify(data, null, 4);
    const filepath = "tsconfig.json";
    const config = await resolveConfig(filepath, { editorconfig: true });
    const formatted = await format(content, { ...config, filepath });
    return formatted;
}

/**
 * @internal
 */
export async function generateApiExtractorLib(
    options: Pick<Options, "apiExtractorReportFolder" | "enableApiExtractor">,
): Promise<string | null> {
    if (!options.enableApiExtractor) {
        return null;
    }
    const config = {
        $schema:
            "https://developer.microsoft.com/json-schemas/api-extractor/v7/api-extractor.schema.json",
        extends:
            "@forsakringskassan/vite-lib-config/api-extractor/api-extractor.json",
        compiler: {
            tsconfigFilePath: "<projectFolder>/tsconfig.lib.json",
        },
        apiReport: {
            reportFileName: "<unscopedPackageName>.api.md",
            reportFolder: options.apiExtractorReportFolder
                ? `<projectFolder>/${options.apiExtractorReportFolder}`
                : undefined,
        },
        docModel: {
            enabled: true,
        },
        dtsRollup: {
            publicTrimmedFilePath: "<projectFolder>/dist/types/index.d.ts",
        },
    };
    return [boilerplate, await serializeJson(config)].join("\n\n");
}

